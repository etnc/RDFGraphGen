"""
Command-line interface of RDFGraphGen.

    rdfgen SHAPES OUTPUT SCALE_FACTOR [--validate]   generate a synthetic RDF graph from SHACL shapes
    rdfgen validate SHAPES DATA                      check whether an RDF graph conforms to SHACL shapes

Exit status: 0 = success (and, when validating, the graph conforms), 1 = the graph does not conform,
2 = usage error or the check could not be performed, 3 = nothing was checked (no focus nodes).
"""
import argparse
import os
import sys
from datetime import datetime

from rdf_graph_gen import __version__

EXIT_OK = 0
EXIT_NONCONFORMING = 1
EXIT_ERROR = 2
EXIT_NOTHING_CHECKED = 3

EXIT_STATUS_HELP = ("Exit status: 0 = success (with validation: the graph conforms), 1 = the graph does not conform, "
                    "2 = error, 3 = nothing was checked (no focus nodes).")

# 'rdfgen validate' loads the whole graph into memory; warn above this size.
LARGE_GRAPH_BYTES = 200 * 1024 * 1024

REPOSITORY_URL = "https://github.com/etnc/RDFGraphGen"


def _positive_int(value):
    try:
        number = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(f"expected a positive integer, got '{value}'")
    if number < 1:
        raise argparse.ArgumentTypeError(f"expected a positive integer, got {number}")
    return number


def build_generate_parser():
    parser = argparse.ArgumentParser(
        prog="rdfgen",
        description="Generate a synthetic RDF graph based on SHACL shapes.",
        epilog="To check whether an existing RDF graph conforms to SHACL shapes, use: rdfgen validate SHAPES DATA "
               f"(see 'rdfgen validate --help'). {EXIT_STATUS_HELP} For more information, visit {REPOSITORY_URL}.")
    parser.add_argument("input_file", help="path to the input file with SHACL shapes")
    parser.add_argument("output_file", help="path to the output file where the generated RDF graph is saved (Turtle)")
    parser.add_argument("scale_factor", type=_positive_int,
                        help="number of entities generated for each top-level node shape; it controls the size of "
                             "the generated RDF graph")
    parser.add_argument("-b", "--batch_size", type=_positive_int, default=1000,
                        help="number of entities generated per batch; batches are generated in parallel and "
                             "written to the output file in order (default: 1000)")
    parser.add_argument("-p", "--processes", type=_positive_int, default=None,
                        help="number of worker processes (default: the number of CPUs)")
    parser.add_argument("-s", "--seed", type=int, default=None,
                        help="seed for the random generator: the same seed always produces the same graph, "
                             "regardless of the number of processes (default: a different graph on every run)")
    parser.add_argument("--validate", action="store_true",
                        help="check that the generated graph conforms to the input shapes and print a summary; "
                             "each batch is checked right after it is generated (requires pySHACL: "
                             "pip install \"rdf-graph-gen[validate]\")")
    parser.add_argument("--report", metavar="FILE",
                        help="with --validate: also write the full SHACL validation report to FILE (Turtle)")
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    return parser


def build_validate_parser():
    parser = argparse.ArgumentParser(
        prog="rdfgen validate",
        description="Check whether an RDF graph conforms to SHACL shapes. Entities generated by RDFGraphGen are "
                    "checked against the shape they were generated from (they link to it via sh:description), so "
                    "the check is meaningful even for shapes without target declarations. Target declarations in "
                    "the shapes apply as usual. The whole graph is loaded into memory; to check large generated "
                    "graphs, use 'rdfgen ... --validate' during generation instead.",
        epilog=f"{EXIT_STATUS_HELP} Requires pySHACL: pip install \"rdf-graph-gen[validate]\".")
    parser.add_argument("shapes_file", help="path to the file with SHACL shapes")
    parser.add_argument("data_file", help="path to the RDF graph to check (e.g. a graph generated by rdfgen)")
    parser.add_argument("--report", metavar="FILE", help="also write the full SHACL validation report to FILE (Turtle)")
    parser.add_argument("--declared-targets-only", action="store_true",
                        help="ignore the provenance links of generated entities and check only the focus nodes "
                             "selected by the target declarations of the shapes (plain SHACL validation)")
    return parser


def main(argv=None):
    argv = sys.argv[1:] if argv is None else list(argv)
    if argv and argv[0] == "validate":
        args = build_validate_parser().parse_args(argv[1:])
        return check_conformance(args.shapes_file, args.data_file, args.report,
                                 use_provenance=not args.declared_targets_only)

    parser = build_generate_parser()
    args = parser.parse_args(argv)
    if args.report and not args.validate:
        parser.error("--report requires --validate")
    return generate(args)


def generate(args):
    from rdf_graph_gen.multiprocess_generate import MultiprocessGenerator

    if args.validate:
        # Fail before a potentially long generation run, not after it
        from rdf_graph_gen.validation import ValidatorUnavailableError, ensure_validator_available
        try:
            ensure_validator_available()
        except ValidatorUnavailableError as error:
            print(f"rdfgen: {error}", file=sys.stderr)
            return EXIT_ERROR

    start = datetime.now()
    generator = MultiprocessGenerator(args.input_file, args.output_file, args.scale_factor, args.batch_size,
                                      processes=args.processes, seed=args.seed, validate=args.validate,
                                      collect_report=bool(args.report))
    summary = generator.generate()
    print(f"Generator ran with {generator.processes} process(es), finished in {datetime.now() - start}.")

    if summary is None:
        return EXIT_OK
    return report_conformance(summary, args.report)


def check_conformance(shapes_file, data_file, report_file=None, use_provenance=True):
    """Validate data_file against shapes_file, print a summary and return the exit status."""
    from rdflib import Graph
    from rdf_graph_gen.validation import ValidatorUnavailableError, validate_generated

    graphs = []
    for path in (shapes_file, data_file):
        try:
            if os.path.getsize(path) > LARGE_GRAPH_BYTES:
                print(f"rdfgen: note: {path} is large; validation loads the whole graph into memory and may be slow.",
                      file=sys.stderr)
            # bind_namespaces="core": prefixes declared in the files win over rdflib's defaults in the summary
            graphs.append(Graph(bind_namespaces="core").parse(path))
        except Exception as error:  # missing file, unreadable file or RDF syntax error
            print(f"rdfgen: cannot read {path}: {error}", file=sys.stderr)
            return EXIT_ERROR
    shapes_graph, data_graph = graphs

    try:
        summary = validate_generated(shapes_graph, data_graph, use_provenance=use_provenance)
    except ValidatorUnavailableError as error:
        print(f"rdfgen: {error}", file=sys.stderr)
        return EXIT_ERROR
    return report_conformance(summary, report_file)


def report_conformance(summary, report_file=None):
    """Print the summary, write the full report if requested, and return the exit status."""
    print(summary.format())
    if report_file and summary.report_graph is not None:
        summary.report_graph.serialize(destination=report_file, format="turtle")
        print(f"Full validation report written to {report_file}")
    if summary.vacuous:
        return EXIT_NOTHING_CHECKED
    return EXIT_OK if summary.conforms else EXIT_NONCONFORMING


if __name__ == "__main__":
    sys.exit(main())
