"""
Conformance checking of RDF graphs against SHACL shapes, with support for graphs generated by RDFGraphGen.

What "conforms" means here: SHACL only validates the focus nodes selected by target declarations
(sh:targetClass, sh:targetNode, ...). Many shapes graphs used for generation declare no targets at all, so a
plain SHACL validation of the generated data would check nothing and report "conforms" vacuously. Therefore,
in addition to the focus nodes selected by the target declarations, every generated entity is validated
against the shape it was generated from: the generator links each entity to its source shape with a
provenance triple (entity sh:description shape). A generated graph conforms if every generated entity
conforms to its source shape and every focus node selected by the target declarations conforms to its shape.

For each source shape, the validation shapes graph gets a copy of the shape whose sh:targetNode declarations
select the entities generated from it. The original shapes are left unchanged, which keeps validation linear
in the size of the data: SHACL processors read all triples of a shape each time they evaluate it, including
for every value of a sh:node reference to it, so adding one target triple per entity to the original shape
would make validation quadratic.

The validation itself is performed by pySHACL, an optional dependency
(pip install "rdf-graph-gen[validate]"). Note that the SHACL specification leaves the semantics of recursive
shapes undefined; for such shapes, the results follow pySHACL's interpretation.
"""
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from typing import Optional

from rdflib import BNode, Graph, Literal, RDF, RDFS, SH, URIRef

# Predicate the generator uses to link a generated entity to the shape it was generated from.
PROVENANCE_PREDICATE = SH.description

_COMPONENT_SUFFIX = "ConstraintComponent"
_TARGET_PREDICATES = (SH.targetNode, SH.targetClass, SH.targetSubjectsOf, SH.targetObjectsOf)


class ValidatorUnavailableError(RuntimeError):
    """Raised when pySHACL, the optional validation backend, is not installed."""


def ensure_validator_available():
    """Raise ValidatorUnavailableError if pySHACL cannot be imported."""
    try:
        import pyshacl  # noqa: F401
    except ImportError as error:
        raise ValidatorUnavailableError(
            "SHACL validation requires pySHACL. Install it with: pip install \"rdf-graph-gen[validate]\""
        ) from error


@dataclass
class ValidationSummary:
    """The outcome of a conformance check, with counts that show what was actually checked."""

    conforms: bool
    focus_nodes: int  # distinct focus nodes that were checked
    provenance_focus_nodes: int  # entities checked against the shape they were generated from
    declared_focus_nodes: int  # focus nodes selected by the target declarations of the shapes
    violating_focus_nodes: int  # distinct focus nodes with at least one validation result
    root_cause_focus_nodes: int  # ... of which have at least one result that is not propagated (see below)
    results_by_severity: Counter  # e.g. {"Violation": 12}
    results_by_constraint: Counter  # {(constraint parameter, path): count}, e.g. {("sh:minLength", "ex:name"): 3}
    # The subset of results_by_constraint that is only propagated from a nested entity: sh:node results whose
    # value node is itself a focus node with validation results (its own results show the actual cause).
    propagated_results: Counter = field(default_factory=Counter)
    report_graph: Optional[Graph] = field(default=None, repr=False)  # the full SHACL validation report
    used_provenance: bool = True  # whether provenance links were used to select focus nodes

    @property
    def vacuous(self):
        """True if no focus node was checked, i.e. a positive result would say nothing about the data."""
        return self.focus_nodes == 0

    def format(self, max_rows=25):
        """A human-readable summary of the check."""
        if self.vacuous:
            if self.used_provenance:
                reason = ("the shapes declare no targets that match the data, and the data has no\n"
                          "  provenance links (sh:description) to the shapes")
            else:
                reason = "the shapes declare no targets that match the data (provenance links were ignored)"
            return (f"Conformance check: NOTHING CHECKED\n"
                    f"  No focus nodes were selected: {reason}. A 'conforms' result would be vacuous here.")

        lines = [f"Conformance check: {'CONFORMS' if self.conforms else 'DOES NOT CONFORM'}",
                 f"  Focus nodes checked: {self.focus_nodes} "
                 f"({self.provenance_focus_nodes} against the shape they were generated from, "
                 f"{self.declared_focus_nodes} selected by target declarations)"]
        if self.violating_focus_nodes:
            share = 100.0 * self.violating_focus_nodes / self.focus_nodes
            lines.append(f"  Focus nodes with validation results: {self.violating_focus_nodes} ({share:.1f}%)")
            only_propagated = self.violating_focus_nodes - self.root_cause_focus_nodes
            if only_propagated:
                lines.append(f"    of which {only_propagated} only because a nested entity does not conform")
            if set(self.results_by_severity) != {"Violation"}:
                severities = ", ".join(f"{count} {name}" for name, count in self.results_by_severity.most_common())
                lines.append(f"  Results by severity: {severities}")
            lines.append("  Results by constraint (count, constraint, path):")
            rows = sorted(self.results_by_constraint.items(), key=lambda row: (-row[1], row[0]))
            width = max(len(constraint) for (constraint, _), _ in rows)
            for key, count in rows[:max_rows]:
                constraint, path = key
                note = ""
                propagated = self.propagated_results.get(key, 0)
                if propagated == count:
                    note = "  [nested entity does not conform]"
                elif propagated:
                    note = f"  [{propagated} of them: nested entity does not conform]"
                lines.append(f"    {count:>8}  {constraint:<{width}}  {path or '(focus node)'}{note}")
            if len(rows) > max_rows:
                lines.append(f"    ... and {len(rows) - max_rows} more (see the full report)")
        return "\n".join(lines)


def validate_generated(shapes_graph, data_graph, use_provenance=True, declared_target_nodes=True):
    """
    Check whether data_graph conforms to the shapes in shapes_graph.

    With use_provenance=True (the default), each entity that the generator linked to a shape of shapes_graph
    (entity sh:description shape) is validated against that shape, in addition to the focus nodes selected by
    the target declarations of the shapes. With use_provenance=False, this is a plain SHACL validation.

    With declared_target_nodes=False, sh:targetNode declarations of the shapes are ignored. This is used when a
    generated graph is validated batch by batch: the constant nodes selected by sh:targetNode are the same in
    every batch, so they are checked only once.

    Returns a ValidationSummary. Raises ValidatorUnavailableError if pySHACL is not installed.
    """
    ensure_validator_available()
    from pyshacl import validate

    validation_shapes, provenance_nodes, declared_nodes = build_validation_shapes(
        shapes_graph, data_graph, use_provenance, declared_target_nodes)

    conforms, report_graph, _ = validate(data_graph, shacl_graph=validation_shapes, inference="none",
                                         abort_on_first=False, allow_infos=False, allow_warnings=False)

    namespaces = shapes_graph.namespace_manager
    results = []
    # Only the results of the report itself (sh:result); results nested in them via sh:detail (e.g. why a
    # value node does not conform to a sh:node shape) are explanations, not additional results.
    for result in set(report_graph.objects(None, SH.result)):
        component = report_graph.value(result, SH.sourceConstraintComponent)
        path = report_graph.value(result, SH.resultPath)
        severity = report_graph.value(result, SH.resultSeverity)
        results.append((report_graph.value(result, SH.focusNode), report_graph.value(result, SH.value), component,
                        (_constraint_label(component, namespaces), _path_label(path, namespaces)),
                        _local_name(severity) if severity is not None else "Unknown"))

    violating_nodes = {focus for focus, _, _, _, _ in results if focus is not None}
    by_severity, by_constraint, propagated, root_cause_nodes = Counter(), Counter(), Counter(), set()
    for focus, value, component, key, severity in results:
        by_severity[severity] += 1
        by_constraint[key] += 1
        # A sh:node result on a value node that has results of its own is a consequence of those results.
        # (For sh:node on a node shape, the value node is the focus node itself: that is a root cause.)
        if component == SH.NodeConstraintComponent and value != focus and value in violating_nodes:
            propagated[key] += 1
        elif focus is not None:
            root_cause_nodes.add(focus)

    return ValidationSummary(
        conforms=bool(conforms),
        focus_nodes=len(provenance_nodes | declared_nodes),
        provenance_focus_nodes=len(provenance_nodes),
        declared_focus_nodes=len(declared_nodes),
        violating_focus_nodes=len(violating_nodes),
        root_cause_focus_nodes=len(root_cause_nodes),
        results_by_severity=by_severity,
        results_by_constraint=by_constraint,
        propagated_results=propagated,
        report_graph=report_graph,
        used_provenance=use_provenance,
    )


def build_validation_shapes(shapes_graph, data_graph, use_provenance=True, declared_target_nodes=True):
    """
    Build the shapes graph that is used for validation (see the module documentation), without changing
    shapes_graph. Returns (validation shapes graph, provenance focus nodes, declared focus nodes).
    """
    validation_shapes = Graph()
    validation_shapes += shapes_graph
    if not declared_target_nodes:
        validation_shapes.remove((None, SH.targetNode, None))

    declared_by_shape = {shape: _declared_focus_nodes_of(shape, shapes_graph, data_graph, declared_target_nodes)
                         for shape in _shapes_with_targets(shapes_graph)}
    declared_nodes = set().union(*declared_by_shape.values())

    provenance_nodes = set()
    if use_provenance:
        generated_from = defaultdict(set)
        known_shapes = _shape_nodes(shapes_graph)
        for node, shape in data_graph.subject_objects(PROVENANCE_PREDICATE):
            if shape in known_shapes:
                generated_from[shape].add(node)
        for shape, nodes in generated_from.items():
            provenance_nodes |= nodes
            # Nodes that the shape's own targets select are validated against it anyway
            extra_nodes = nodes - declared_by_shape.get(shape, set())
            if extra_nodes:
                _add_targeted_copy(validation_shapes, shapes_graph, shape, extra_nodes)
    return validation_shapes, provenance_nodes, declared_nodes


class ValidationAccumulator:
    """
    Combines the summaries of separately validated, disjoint parts of a graph (e.g. the batches of a generation
    run) into one summary, and optionally their reports into one SHACL validation report.
    """

    def __init__(self, collect_report=False):
        self._summary = None
        self._report = Graph() if collect_report else None
        self._report_node = BNode()

    def add(self, summary, report_text=None):
        """Add the summary of one part; report_text is the part's validation report in N-Triples, if collected."""
        if self._summary is None:
            self._summary = ValidationSummary(
                conforms=True, focus_nodes=0, provenance_focus_nodes=0, declared_focus_nodes=0,
                violating_focus_nodes=0, root_cause_focus_nodes=0, results_by_severity=Counter(),
                results_by_constraint=Counter(), used_provenance=summary.used_provenance)
        total = self._summary
        total.conforms = total.conforms and summary.conforms
        for name in ("focus_nodes", "provenance_focus_nodes", "declared_focus_nodes", "violating_focus_nodes",
                     "root_cause_focus_nodes"):
            setattr(total, name, getattr(total, name) + getattr(summary, name))
        total.results_by_severity.update(summary.results_by_severity)
        total.results_by_constraint.update(summary.results_by_constraint)
        total.propagated_results.update(summary.propagated_results)

        if self._report is not None and report_text:
            part = Graph().parse(data=report_text, format="nt")  # blank nodes are scoped to this part
            part_reports = set(part.subjects(RDF.type, SH.ValidationReport))
            for report in part_reports:
                for result in part.objects(report, SH.result):
                    self._report.add((self._report_node, SH.result, result))
            for triple in part:
                if triple[0] not in part_reports:
                    self._report.add(triple)

    def summary(self):
        """The combined summary; its report_graph is the combined report, if reports were collected."""
        total = self._summary or ValidationSummary(
            conforms=True, focus_nodes=0, provenance_focus_nodes=0, declared_focus_nodes=0, violating_focus_nodes=0,
            root_cause_focus_nodes=0, results_by_severity=Counter(), results_by_constraint=Counter())
        if self._report is not None:
            self._report.add((self._report_node, RDF.type, SH.ValidationReport))
            self._report.add((self._report_node, SH.conforms, Literal(total.conforms)))
            total.report_graph = self._report
        return total


def _shape_nodes(shapes_graph):
    return set(shapes_graph.subjects(RDF.type, SH.NodeShape)) | set(shapes_graph.subjects(RDF.type, SH.PropertyShape))


def _shapes_with_targets(shapes_graph):
    """Shapes with explicit target declarations, and shapes that are also classes (implicit class targets)."""
    shapes = {s for p in _TARGET_PREDICATES for s in shapes_graph.subjects(p, None)}
    shapes |= {s for s in _shape_nodes(shapes_graph) if (s, RDF.type, RDFS.Class) in shapes_graph}
    return shapes


def _add_targeted_copy(validation_shapes, shapes_graph, shape, nodes):
    """Add a copy of `shape` (without its targets) that targets `nodes`; the original shape stays unchanged."""
    copy = BNode()
    for predicate, value in shapes_graph.predicate_objects(shape):
        if predicate == RDF.type:
            if value in (SH.NodeShape, SH.PropertyShape):
                validation_shapes.add((copy, predicate, value))
        elif predicate not in _TARGET_PREDICATES:
            validation_shapes.add((copy, predicate, value))
    for node in nodes:
        validation_shapes.add((copy, SH.targetNode, node))


def _instances(data_graph, cls):
    # SHACL instances of a class: nodes typed with the class or one of its (transitive) subclasses in the data graph
    classes = set(data_graph.transitive_subjects(RDFS.subClassOf, cls))
    classes.add(cls)
    return {node for c in classes for node in data_graph.subjects(RDF.type, c)}


def _declared_focus_nodes_of(shape, shapes_graph, data_graph, include_target_nodes=True):
    """The focus nodes selected by the target declarations of one shape (SHACL section 2.1.3)."""
    nodes = set(shapes_graph.objects(shape, SH.targetNode)) if include_target_nodes else set()
    for cls in shapes_graph.objects(shape, SH.targetClass):
        nodes |= _instances(data_graph, cls)
    if (shape, RDF.type, RDFS.Class) in shapes_graph:  # implicit class target
        nodes |= _instances(data_graph, shape)
    for predicate in shapes_graph.objects(shape, SH.targetSubjectsOf):
        nodes.update(data_graph.subjects(predicate, None))
    for predicate in shapes_graph.objects(shape, SH.targetObjectsOf):
        nodes.update(data_graph.objects(None, predicate))
    return nodes


def _local_name(iri):
    text = str(iri)
    return text.rsplit("#", 1)[-1].rsplit("/", 1)[-1]


def _constraint_label(component, namespaces):
    """sh:MinLengthConstraintComponent -> 'sh:minLength' (the constraint parameter users write in their shapes)."""
    if component is None:
        return "(unknown)"
    if isinstance(component, URIRef) and str(component).startswith(str(SH)):
        name = str(component)[len(str(SH)):]
        if name.endswith(_COMPONENT_SUFFIX):
            name = name[:-len(_COMPONENT_SUFFIX)]
            name = "sparql" if name == "SPARQL" else name[0].lower() + name[1:]
        return f"sh:{name}"
    return component.n3(namespaces)


def _path_label(path, namespaces):
    if path is None:
        return ""
    if isinstance(path, URIRef):
        return path.n3(namespaces)
    return "(complex path)"
